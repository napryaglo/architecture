import { Border, DockPanel, PageView, StackPanel, TextBlock, TreeView } from "@visualisation-sub/mural/Controls";
import { Application, Color, NameScope, Thickness } from "@visualisation-sub/mural/runtime";
import { FontWeight, SolidColorBrush } from "@visualisation-sub/mural/visual-engine";

export const app = (() => {
    const _app0 = new Application();
    const _rd1 = _app0.Resources;
    _rd1.Set("paper", new SolidColorBrush(Color.FromHex('#ffffff')));
    _rd1.Set("hairline", new SolidColorBrush(Color.FromHex('#e2e8f0')));
    _rd1.Set("primary", new SolidColorBrush(Color.FromHex('#1976d2')));
    _rd1.Set("primInk", new SolidColorBrush(Color.FromHex('#ffffff')));
    _rd1.Set("navBg", new SolidColorBrush(Color.FromHex('#f8fafc')));
    const _border2 = new Border();
    _border2.SetNameScope(new NameScope());
    _border2.set_property_value("Background", Application.current.Resources.Resolve("paper"));
    const _dockPanel3 = new DockPanel();
    const _border4 = new Border();
    _border4.set_property_value(DockPanel, "Dock", "Left");
    _border4.set_property_value("Width", 260);
    _border4.set_property_value("Background", Application.current.Resources.Resolve("navBg"));
    _border4.set_property_value("BorderBrush", Application.current.Resources.Resolve("hairline"));
    _border4.set_property_value("BorderThickness", new Thickness(0, 0, 1, 0));
    const _stackPanel5 = new StackPanel();
    const _border6 = new Border();
    _border6.set_property_value("Background", Application.current.Resources.Resolve("primary"));
    _border6.set_property_value("Padding", new Thickness(20, 16, 20, 16));
    const _textBlock7 = new TextBlock();
    _textBlock7.set_property_value("Text", "µ-mural demos");
    _textBlock7.set_property_value("FontSize", 14);
    _textBlock7.set_property_value("FontWeight", FontWeight.Bold);
    _textBlock7.set_property_value("Foreground", Application.current.Resources.Resolve("primInk"));
    _border6.SetChild(_textBlock7);
    _stackPanel5.AddChild(_border6);
    const _treeView8 = new TreeView();
    _treeView8.Name = "nav";
    _border2.nameScope.Register("nav", _treeView8);
    _treeView8.set_property_value("Indent", 18);
    _treeView8.set_property_value("Margin", new Thickness(8, 8, 8, 8));
    _stackPanel5.AddChild(_treeView8);
    _border4.SetChild(_stackPanel5);
    _dockPanel3.AddChild(_border4);
    const _pageView9 = new PageView();
    _pageView9.Name = "page";
    _border2.nameScope.Register("page", _pageView9);
    _pageView9.set_property_value("Title", "");
    _pageView9.set_property_value("Subtitle", "");
    _dockPanel3.AddChild(_pageView9);
    _border2.SetChild(_dockPanel3);
    _rd1.Root = _border2;
    return _app0;
})();
