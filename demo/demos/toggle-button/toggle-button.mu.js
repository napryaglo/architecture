        _textBlock25._set_property_value_by_name("Text", DataContextBinding(_textBlock25, "PreviewText"));
        _textBlock25._set_property_value_by_name("FontSize", 16);
        _textBlock25._set_property_value_by_name("Foreground", DynamicResource(_textBlock25, "OnSurface"));
        _stackPanel24.AddChild(_textBlock25);
