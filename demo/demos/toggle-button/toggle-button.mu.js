        _border23._set_property_value_by_name("Background", DynamicResource(_border23, "SurfaceContainerLow"));
        _border23._set_property_value_by_name("Padding", new Thickness(12, 12, 12, 12));
        _border23._set_property_value_by_name("BorderBrush", DynamicResource(_border23, "Outline"));
        _border23._set_property_value_by_name("BorderThickness", new Thickness(1));
